#!/usr/bin/env python3
"""Build a compact table-of-contents for ota-ledger.md (date + one-line headline + line number),
so a run can grep this instead of loading the full (500KB+) ledger prose.
Usage: python3 bin/ledger-index.py > ota-ledger-index.md
"""
import re
import sys
from pathlib import Path

LEDGER = Path(__file__).resolve().parent.parent / "ota-ledger.md"
ENTRY_RE = re.compile(r"^-\s+(2026-\d\d-\d\d)\s+\(([^)]*)\)\s*(?:—|-)?\s*(.*)$")
ENTRY_RE_BOLD = re.compile(r"^\*\*(2026-\d\d-\d\d)\s+([^*]*?)\.?\*\*\s*(.*)$")
BOLD_RE = re.compile(r"\*\*(.*?)\*\*")


def headline(rest: str) -> str:
    m = BOLD_RE.search(rest)
    if m:
        return m.group(1).strip()
    return rest.strip()[:160]


def main() -> int:
    lines = LEDGER.read_text(encoding="utf-8", errors="replace").splitlines()
    rows = []
    for i, line in enumerate(lines, start=1):
        m = ENTRY_RE.match(line)
        if m:
            date, ctx, rest = m.groups()
            rows.append((date, headline(rest), i, ctx.strip()))
            continue
        m2 = ENTRY_RE_BOLD.match(line)
        if m2:
            date, ctx, rest = m2.groups()
            rows.append((date, headline(rest), i, ctx.strip()))

    print("<!-- auto-generated by bin/ledger-index.py — do not hand-edit; regenerate after adding ledger entries -->")
    print(f"# ota-ledger.md index ({len(rows)} entries)")
    print()
    print("One line per dated entry: date, one-line headline (its bold claim), and the line number")
    print("in ota-ledger.md to jump to for the full entry. Read THIS file first to find the right")
    print("date/topic, then `sed -n '<line>,+40p' ota-ledger.md` (or grep the date) for the prose —")
    print("don't Read the full ota-ledger.md (500KB+, exceeds the Read tool's size limit).")
    print()
    for date, head, lineno, ctx in rows:
        print(f"- L{lineno} {date} — {head}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
